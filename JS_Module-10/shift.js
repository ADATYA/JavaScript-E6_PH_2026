//All about Shift Method...

const numbers = [1, 2, 3, 4, 5];

numbers.shift();
console.log(numbers); //Shift method removes the first element from the array list.


// All about Unshift Method...

const numbers1 = [12, 13, 14, 15, 16];
numbers1.unshift(10);
console.log(numbers1); //Shift method removes the first element from the array list.
